var profiles = []profile{portainerProfile, arcaneProfile}

// write builds one profile and writes its catalog file.
func write(p profile) error {
	out, err := buildProfile(p)
	if err != nil {
		return err
	}
	body, err := yaml.Marshal(out)
	if err != nil {
		return err
	}
	// #nosec G306 -- a generated repository file must stay group/world readable.
	if err := os.WriteFile(p.out, append([]byte(p.header), body...), 0o644); err != nil {
		return err
	}
	printCounts(p.name, out)
	return nil
}

func printCounts(name string, out *catalog.Catalog) {
	total, on := 0, 0
	for _, ts := range out.Toolsets {
		d := 0
		for _, t := range ts.Tools {
			if t.Default {
				d++
			}
		}
		total += len(ts.Tools)
		on += d
		fmt.Fprintf(os.Stderr, "  %-14s %3d tools, %2d default\n", ts.Name, len(ts.Tools), d)
	}
	fmt.Fprintf(os.Stderr, "cataloggen %s: %d tools (%d default)\n", name, total, on)
}

// build derives the Portainer catalog from the curated mapping and both documents.
func build() (*catalog.Catalog, error) {
	return buildProfile(portainerProfile)
}

// buildProfile derives one server's catalog from its curated mapping.
func buildProfile(p profile) (*catalog.Catalog, error) {
	raw, err := os.ReadFile(p.toolsets)
	if err != nil {
		return nil, err
	}
	var m mapping
	if err := yaml.Unmarshal(raw, &m); err != nil {
		return nil, fmt.Errorf("%s: %w", p.toolsets, err)
	}
	if m.Version != 1 {
		return nil, fmt.Errorf("%s: unsupported version %d", p.toolsets, m.Version)
	}

	raw, err = os.ReadFile(p.defaults)
	if err != nil {
		return nil, err
	}
	var def defaults
	if err := yaml.Unmarshal(raw, &def); err != nil {
		return nil, fmt.Errorf("%s: %w", p.defaults, err)
	}

	curated, err := os.ReadFile(p.meta)
	if err != nil {
		return nil, err
	}
	var meta catalog.Catalog
	if err := yaml.Unmarshal(curated, &meta); err != nil {
		return nil, fmt.Errorf("%s: %w", p.meta, err)
	}

	specs, err := loadSpecs(p.sources)
	if err != nil {
		return nil, err
	}
	ops, err := collectOps(m, specs)
	if err != nil {
		return nil, err
	}

	byToolset := make(map[string][]catalog.Tool, len(m.Toolsets))
	seen := make(map[string]string)
	defaultsOn := make(map[string]bool, len(def.Tools))
	for _, name := range def.Tools {
		defaultsOn[name] = true
	}
	countByID := make(map[string]int, len(ops))
	for _, op := range ops {
		countByID[op.id]++
	}
	matched := make(map[string]bool, len(def.Tools))

	for _, op := range ops {
		toolset, ok := m.Overrides[op.id]
		if !ok {
			toolset, ok = m.Tags[op.source][firstTag(op.tags)]
		}
		if !ok {
			return nil, fmt.Errorf("%s %s %s: no toolset for tags %v", op.source, op.method, op.path, op.tags)
		}
		name, err := toolName(m, op)
		if err != nil {
			return nil, err
		}
		if prev, dup := seen[name]; dup {
			return nil, fmt.Errorf("duplicate tool %q from %s and %s %s %s", name, prev, op.source, op.method, op.path)
		}
		seen[name] = op.source + " " + op.method + " " + op.path
		tool := buildTool(m, op, toolset, name, p.instance)
		key := ""
		switch {
		case defaultsOn[name]:
			key = name
		case defaultsOn[op.source+"/"+op.id]:
			key = op.source + "/" + op.id
		case defaultsOn[op.id]:
			// An operationId that both documents use needs the source prefix.
			if countByID[op.id] > 1 {
				return nil, fmt.Errorf("%s: %q is ambiguous, write %q or %q", p.defaults, op.id, "portainer/"+op.id, "docker/"+op.id)
			}
			key = op.id
		}
		if key != "" {
			if matched[key] {
				return nil, fmt.Errorf("%s: %q matched more than one operation", p.defaults, key)
			}
			matched[key] = true
			tool.Default = true
		}
		byToolset[toolset] = append(byToolset[toolset], tool)
	}

	for _, ex := range m.Extras {
		tool, err := extraTool(m, ex, p.instance)
		if err != nil {
			return nil, err
		}
		if prev, dup := seen[tool.Name]; dup {
			return nil, fmt.Errorf("duplicate tool %q from %s and extras", tool.Name, prev)
		}
		seen[tool.Name] = "extras"
		if defaultsOn[tool.Name] {
			if matched[tool.Name] {
				return nil, fmt.Errorf("%s: %q matched more than one tool", p.defaults, tool.Name)
			}
			matched[tool.Name] = true
			tool.Default = true
		}
		byToolset[ex.Toolset] = append(byToolset[ex.Toolset], tool)
	}

	if len(matched) != len(def.Tools) {
		var missing []string
		for _, name := range def.Tools {
			if !matched[name] {
				missing = append(missing, name)
			}
		}
		return nil, fmt.Errorf("%s: %d entries matched no operation: %s", p.defaults, len(missing), strings.Join(missing, ", "))
	}

	out := catalog.Catalog{Version: 1}
	known := make(map[string]bool, len(meta.Toolsets))
	for _, ts := range meta.Toolsets {
		known[ts.Name] = true
	}
	for _, name := range m.Toolsets {
		if !known[name] {
			return nil, fmt.Errorf("toolset %q is in %s but not in %s", name, p.toolsets, p.meta)
		}
		tools := byToolset[name]
		if len(tools) == 0 {
			return nil, fmt.Errorf("toolset %q has no tools", name)
		}
		sort.Slice(tools, func(i, j int) bool { return tools[i].Name < tools[j].Name })
		out.Toolsets = append(out.Toolsets, catalog.Toolset{Name: name, Tools: tools})
	}
	for _, ts := range meta.Toolsets {
		if len(byToolset[ts.Name]) == 0 {
			return nil, fmt.Errorf("toolset %q is in %s but has no tools", ts.Name, p.meta)
		}
	}

	return &out, nil
}

func loadSpecs(srcs []source) ([]*spec, error) {
	out := make([]*spec, 0, len(srcs))
	for _, s := range srcs {
		data, err := os.ReadFile(s.file)
		if err != nil {
			return nil, err
		}
		var doc map[string]any
		if err := yaml.Unmarshal(data, &doc); err != nil {
			return nil, fmt.Errorf("%s: %w", s.file, err)
		}
		prefix := s.prefix
		if prefix == "" {
			// Docker Engine paths are used without a version prefix: the daemon
			// then serves the version it implements.
			prefix = "/api/endpoints/{environment}/docker"
		}
		out = append(out, &spec{source: s.name, prefix: prefix, doc: doc})
	}
	return out, nil
}

// anyTagSkipped reports whether any of the operation's tags is excluded. An
// operation tagged Auth and Passkeys belongs to the excluded topic even when
// Auth comes first.
func anyTagSkipped(tags []string, skip map[string]bool) bool {
	for _, t := range tags {
		if skip[t] {
			return true
		}
	}
	return false
}

func collectOps(m mapping, specs []*spec) ([]*operation, error) {
	skip := make(map[string]bool, len(m.SkipTags))
	for _, t := range m.SkipTags {
		skip[t] = true
	}
	skipPath := make(map[string]bool, len(m.SkipPaths))
	for _, p := range m.SkipPaths {
		skipPath[p] = true
	}
	skipMethod := make(map[string]bool, len(m.SkipMethods))
	for _, x := range m.SkipMethods {
		skipMethod[strings.ToLower(x)] = true
	}
	var out []*operation
	for _, sp := range specs {
		paths, _ := sp.doc["paths"].(map[string]any)
		names := make([]string, 0, len(paths))
		for p := range paths {
			names = append(names, p)
		}
		sort.Strings(names)
		for _, p := range names {
			item, _ := paths[p].(map[string]any)
			for _, method := range []string{"get", "post", "put", "patch", "delete", "head"} {
				rawOp, ok := item[method].(map[string]any)
				if !ok {
					continue
				}
				if anyTagSkipped(strs(rawOp["tags"]), skip) || skipPath[p] || skipMethod[method] {
					continue
				}
				op, err := parseOp(m, sp, method, p, rawOp, list(item["parameters"]))
				if err != nil {
					return nil, err
				}
				out = append(out, op)
			}
		}
	}
	return out, nil
}

// parseOp reads one operation. Parameters declared on the path item apply to
// every method under it, so they are merged in; the operation's own entry wins.
func parseOp(m mapping, sp *spec, method, path string, raw map[string]any, itemParams []any) (*operation, error) {
	op := &operation{
		source:      sp.source,
		method:      strings.ToUpper(method),
		path:        renameParams(m, sp.prefix+path),
		summary:     str(raw["summary"]),
		description: str(raw["description"]),
		tags:        strs(raw["tags"]),
	}
	if id := str(raw["operationId"]); id != "" {
		op.id = id
	} else {
		key := op.method + " " + path
		id, ok := m.Unnamed[key]
		if !ok {
			return nil, fmt.Errorf("%s %s has no operationId and no api/toolsets.yaml unnamed entry for %q", op.method, path, key)
		}
		op.id = id
	}

	type key struct{ name, in string }
	params := list(raw["parameters"])
	seen := make(map[key]bool, len(params))
	for _, p := range params {
		if pm, ok := p.(map[string]any); ok {
			seen[key{str(pm["name"]), str(pm["in"])}] = true
		}
	}
	for _, p := range itemParams {
		pm, ok := p.(map[string]any)
		if !ok || seen[key{str(pm["name"]), str(pm["in"])}] {
			continue
		}
		params = append(params, p)
	}

	for _, p := range params {
		pm, _ := p.(map[string]any)
		if pm == nil {
			return nil, fmt.Errorf("%s %s: parameters must be objects", op.method, path)
		}
		pm = resolve(sp, pm)
		if str(pm["in"]) == "body" {
			op.body = true
			op.bodyReq = boolVal(pm["required"])
			op.bodyDesc = str(pm["description"])
			if d, ok := pm["description"].(string); ok && d == "" {
				op.bodyDesc = ""
			}
			continue
		}
		schema, _ := pm["schema"].(map[string]any)
		if schema == nil {
			schema = swaggerSchema(pm)
		}
		if d := str(pm["description"]); d != "" {
			if _, ok := schema["description"]; !ok {
				schema["description"] = d
			}
		}
		op.params = append(op.params, param{
			name:     renameOne(m, str(pm["name"])),
			in:       str(pm["in"]),
			required: boolVal(pm["required"]) || str(pm["in"]) == "path",
			schema:   schema,
			csv:      str(pm["collectionFormat"]) == "csv" || str(pm["style"]) == "form" && pm["explode"] == false,
		})
	}

	if rb, ok := resolve(sp, raw)["requestBody"].(map[string]any); ok {
		op.body = true
		op.bodyReq = boolVal(rb["required"])
		op.bodyDesc = str(rb["description"])
		op.form = formOnly(rb)
	}

	if resp, ok := raw["responses"].(map[string]any); ok {
		if r200, ok := resp["200"].(map[string]any); ok {
			op.resp = response200(r200)
		}
	}
	return op, nil
}

// resolve follows a $ref inside the document, so a parameter or a request body
// declared once in components is read like an inline one.
func resolve(sp *spec, m map[string]any) map[string]any {
	ref, _ := m["$ref"].(string)
	if ref == "" {
		return m
	}
	node := any(sp.doc)
	for _, part := range strings.Split(strings.TrimPrefix(ref, "#/"), "/") {
		obj, ok := node.(map[string]any)
		if !ok {
			return m
		}
		node = obj[part]
	}
	if out, ok := node.(map[string]any); ok {
		return out
	}
	return m
}

// formOnly reports whether a request body accepts multipart/form-data and no
// JSON at all. Such an operation cannot be called with a JSON body: Portainer
// parses the fields of the form and sees an empty request otherwise.
func formOnly(rb map[string]any) bool {
	content, _ := rb["content"].(map[string]any)
	if _, ok := content["application/json"]; ok {
		return false
	}
	_, form := content["multipart/form-data"]
	return form
}

// response200 returns the 200 response body schema, if any.
func response200(r map[string]any) map[string]any {
	if content, ok := r["content"].(map[string]any); ok {
		if media, ok := content["application/json"].(map[string]any); ok {
			if s, ok := media["schema"].(map[string]any); ok {
				return s
			}
		}
	}
	if s, ok := r["schema"].(map[string]any); ok {
		return s
	}
	return nil
}

// swaggerSchema builds a schema from a Swagger 2.0 parameter's inline fields.
func swaggerSchema(p map[string]any) map[string]any {
	out := map[string]any{}
	for _, k := range []string{"type", "format", "items", "enum", "default", "minimum", "maximum", "pattern", "description"} {
		if v, ok := p[k]; ok {
			out[k] = v
		}
	}
	if _, ok := out["type"]; !ok {
		out["type"] = "string"
	}
	return out
}

func buildTool(m mapping, op *operation, toolset, name, instance string) catalog.Tool {
	props := map[string]any{}
	required := []string{}
	var csv []string

	if op.source == "docker" {
		props["environment"] = map[string]any{
			"type":        "integer",
			"description": "Portainer environment id that owns the Docker endpoint. Find it with environment_list.",
		}
		required = append(required, "environment")
	}
	for _, p := range op.params {
		if p.in != "path" && p.in != "query" {
			continue
		}
		schema := deepCopy(p.schema)
		delete(schema, "$ref")
		if _, ok := schema["type"]; !ok {
			schema["type"] = "string"
		}
		props[p.name] = schema
		if p.required {
			required = append(required, p.name)
		}
		if p.in == "query" && p.csv {
			csv = append(csv, p.name)
		}
	}
	if op.body {
		desc := op.bodyDesc
		if op.form && desc == "" {
			desc = "Form fields, sent as multipart/form-data. A value {filename, content} or {filename, base64} is sent as a file part."
		}
		if desc == "" {
			desc = "JSON request body, passed to the API unchanged."
		}
		props["body"] = map[string]any{
			"type":                 "object",
			"description":          clip(desc, 300),
			"additionalProperties": true,
		}
		if op.bodyReq {
			required = append(required, "body")
		}
	}
	props["instance"] = map[string]any{
		"type":        "string",
		"description": instance,
	}
	sort.Strings(required)
	sort.Strings(csv)

	input := map[string]any{
		"type":                 "object",
		"properties":           props,
		"additionalProperties": false,
	}
	if len(required) > 0 {
		input["required"] = required
	}
	tool := catalog.Tool{
		Name:        name,
		Description: describe(op),
		Annotations: annotations(op.method),
		Input:       input,
		Operation: catalog.Operation{
			Method: op.method,
			Path:   op.path,
			CSV:    csv,
		},
		StreamingPath:      containsAny(op.path, m.StreamPaths),
		StripManagedFields: containsAny(op.path, m.StripPaths),
	}
	for _, p := range m.StreamParams {
		// Only a property the operation declares can arrive in the arguments.
		if _, ok := props[p]; ok {
			tool.StreamingParams = append(tool.StreamingParams, p)
		}
	}
	if op.body {
		tool.Operation.Body = "body"
		tool.Operation.Form = op.form
	}
	if op.form {
		// The note stays whole: a cut description must not lose the one fact
		// the caller needs to build the call.
		const note = " The body is sent as multipart/form-data."
		tool.Description = clip(tool.Description, 400-len(note)) + note
	}
	if out := outputSchema(op.resp); out != nil {
		tool.Output = out
	}
	if ov, ok := m.ToolOverrides[name]; ok {
		if ov.Description != "" {
			tool.Description = clip(ov.Description, 400)
		}
		if ov.ReadOnly != nil {
			tool.Annotations.ReadOnlyHint = ov.ReadOnly
		}
		if ov.Destructive != nil {
			tool.Annotations.DestructiveHint = ov.Destructive
		}
	}
	return tool
}

func extraTool(m mapping, ex extra, instance string) (catalog.Tool, error) {
	if ex.Name == "" || ex.Base == "" {
		return catalog.Tool{}, fmt.Errorf("api/toolsets.yaml: extra needs a name and a base path")
	}
	props := map[string]any{
		"method": map[string]any{
			"type":        "string",
			"enum":        []string{"GET", "POST", "PUT", "PATCH", "DELETE"},
			"description": "HTTP method.",
		},
		"path": map[string]any{
			"type":        "string",
			"description": "API path, starting with /, appended to " + ex.Base + ".",
		},
		"query": map[string]any{
			"type":                 "object",
			"description":          "Query parameters; array values are sent as repeated keys.",
			"additionalProperties": true,
		},
		"body": map[string]any{
			"type":                 "object",
			"description":          "JSON request body, sent unchanged.",
			"additionalProperties": true,
		},
		"instance": map[string]any{
			"type":        "string",
			"description": instance,
		},
	}
	required := []string{"method", "path"}
	if strings.Contains(ex.Base, "{environment}") {
		props["environment"] = map[string]any{
			"type":        "integer",
			"description": "Portainer environment id. Find it with environment_list.",
		}
		required = append(required, "environment")
	}
	return catalog.Tool{
		Name:               ex.Name,
		Description:        clip(ex.Description, 400),
		Annotations:        annotations("POST"), // a raw call may write
		StripManagedFields: containsAny(ex.Base, m.StripPaths),
		Input: map[string]any{
			"type":                 "object",
			"properties":           props,
			"required":             required,
			"additionalProperties": false,
		},
		Operation: catalog.Operation{Path: ex.Base, Raw: true, Body: "body"},
	}, nil
}

// containsAny reports whether path holds one of the fragments. It is how the
// curated fragments in api/toolsets.yaml turn into per-tool flags.
func containsAny(path string, fragments []string) bool {
	for _, f := range fragments {
		if f != "" && strings.Contains(path, f) {
			return true
		}
	}
	return false
}

// annotations are honest: GET and HEAD read, DELETE destroys, PUT repeats
// safely, POST and PATCH are writes that change state.
func annotations(method string) catalog.Annotations {
	yes, no := true, false
	a := catalog.Annotations{OpenWorldHint: &no}
	switch method {
	case "GET", "HEAD":
		a.ReadOnlyHint = &yes
		a.IdempotentHint = &yes
		a.Title = ""
	case "PUT":
		a.ReadOnlyHint = &no
		a.IdempotentHint = &yes
		a.DestructiveHint = &no
	case "DELETE":
		a.ReadOnlyHint = &no
		a.DestructiveHint = &yes
	default: // POST, PATCH
		a.ReadOnlyHint = &no
		a.DestructiveHint = &yes
	}
	return a
}

// outputSchema keeps the shape a client needs — array or object — without
// inlining the referenced component, which would make the catalog megabytes.
func outputSchema(resp map[string]any) map[string]any {
	t, _ := resp["type"].(string)
	switch t {
	case "array":
		return map[string]any{"type": "array", "items": map[string]any{"type": "object", "additionalProperties": true}}
	case "object":
		return map[string]any{"type": "object", "additionalProperties": true}
	case "":
		if ref, ok := resp["$ref"].(string); ok && ref != "" {
			return map[string]any{"type": "object", "additionalProperties": true}
		}
	}
	return nil
}

func describe(op *operation) string {
	text := op.summary
	if text == "" {
		text = firstParagraph(op.description)
	} else if body := firstParagraph(op.description); body != "" && !strings.Contains(text, body) {
		text += " " + body
	}
	if text == "" {
		text = op.method + " " + op.path
	}
	return clip(text, 400)
}

func firstParagraph(s string) string {
	s = strings.TrimSpace(s)
	if s == "" {
		return ""
	}
	if i := strings.Index(s, "\n\n"); i >= 0 {
		s = s[:i]
	}
	return strings.Join(strings.Fields(s), " ")
}

func clip(s string, n int) string {
	s = strings.Join(strings.Fields(s), " ")
	if len(s) <= n {
		return s
	}
	cut := s[:n]
	if i := strings.LastIndex(cut, " "); i > n/2 {
		cut = cut[:i]
	}
	return strings.TrimRight(cut, " ,;:.") + "…"
}

func renameParams(m mapping, path string) string {
	for from, to := range m.Renames {
		path = strings.ReplaceAll(path, "{"+from+"}", "{"+to+"}")
	}
	return path
}

func renameOne(m mapping, name string) string {
	if to, ok := m.Renames[name]; ok {
		return to
	}
	return name
}

func firstTag(tags []string) string {
	if len(tags) == 0 {
		return ""
	}
	return tags[0]
}

func list(v any) []any {
	out, _ := v.([]any)
	return out
}

func strs(v any) []string {
	raw := list(v)
	out := make([]string, 0, len(raw))
	for _, s := range raw {
		if v, ok := s.(string); ok {
			out = append(out, v)
		}
	}
	return out
}

func str(v any) string {
	s, _ := v.(string)
	return s
}

func boolVal(v any) bool {
	b, _ := v.(bool)
	return b
}

func deepCopy(in map[string]any) map[string]any {
	out := make(map[string]any, len(in))
	for k, v := range in {
		if mm, ok := v.(map[string]any); ok {
			out[k] = deepCopy(mm)
			continue
		}
		out[k] = v
	}
	return out
}
