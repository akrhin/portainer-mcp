// Command cataloggen turns the two OpenAPI documents in api/ into the tool
// catalog the server registers. It writes internal/catalog/generated.yaml and
// nothing else; the output must be byte-identical on a second run.
//
//	go run ./tools/cataloggen
package main

import (
	"flag"
	"fmt"
	"os"
	"sort"
	"strings"

	"gopkg.in/yaml.v3"

	"github.com/akrhin/portainer-mcp/internal/catalog"
)

func main() {
	if err := run(); err != nil {
		fmt.Fprintln(os.Stderr, "cataloggen:", err)
		os.Exit(1)
	}
}

type mapping struct {
	Version       int                          `yaml:"version"`
	Toolsets      []string                     `yaml:"toolsets"`
	Tags          map[string]map[string]string `yaml:"tags"`
	Overrides     map[string]string            `yaml:"operation_toolsets"`
	SkipTags      []string                     `yaml:"skip_tags"`
	SkipPaths     []string                     `yaml:"skip_paths"`
	SkipMethods   []string                     `yaml:"skip_methods"`
	Aliases       map[string]string            `yaml:"word_aliases"`
	Rewrites      map[string]string            `yaml:"rewrites"`
	Unnamed       map[string]string            `yaml:"unnamed"`
	Renames       map[string]string            `yaml:"param_renames"`
	Extras        []extra                      `yaml:"extras"`
	StreamParams  []string                     `yaml:"streaming_params"`
	StreamPaths   []string                     `yaml:"streaming_paths"`
	StripPaths    []string                     `yaml:"strip_managed_fields_paths"`
	ToolOverrides map[string]toolOverride      `yaml:"tool_overrides"`
}

// toolOverride replaces what the derived annotation and the spec text say about
// one tool. It exists for a hand-implemented tool whose behaviour the document
// describes imprecisely.
type toolOverride struct {
	Description string `yaml:"description"`
	ReadOnly    *bool  `yaml:"read_only"`
	Destructive *bool  `yaml:"destructive"`
}

type extra struct {
	Name        string `yaml:"name"`
	Toolset     string `yaml:"toolset"`
	Description string `yaml:"description"`
	Base        string `yaml:"base"`
}

type defaults struct {
	Version int      `yaml:"version"`
	Tools   []string `yaml:"tools"`
}

// spec is one OpenAPI document reduced to the pieces the catalog needs.
type spec struct {
	source string // portainer or docker
	prefix string // request path prefix for this source
	doc    map[string]any
}

type param struct {
	name     string
	in       string
	required bool
	schema   map[string]any
	csv      bool // array encoded as one comma-joined value
}

type operation struct {
	source      string
	id          string
	method      string
	path        string
	summary     string
	description string
	tags        []string
	params      []param
	body        bool
	bodyReq     bool
	bodyDesc    string
	form        bool // the body is multipart/form-data only
	resp        map[string]any
}

func run() error {
	only := flag.String("profile", "", "build one profile (portainer or arcane); the default builds every profile")
	flag.Parse()
	found := false
	for _, p := range profiles {
		if *only != "" && *only != p.name {
			continue
		}
		found = true
		if err := write(p); err != nil {
			return err
		}
	}
	if !found {
		return fmt.Errorf("unknown profile %q", *only)
	}
	return nil
}

// profile is one server built from this generator: its documents, the curated
// toolset mapping and metadata, and the file the result is written to.
type profile struct {
	name     string
	sources  []source
	toolsets string // toolset and naming mapping
	defaults string // operations registered without --exhaustive
	meta     string // curated toolset descriptions
	out      string
	header   string
	instance string // description of the instance argument
}

// source is one OpenAPI document and the request path prefix it is served under.
type source struct {
	name, file, prefix string
}

