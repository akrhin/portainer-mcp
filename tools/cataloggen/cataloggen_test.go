// TestBuildMatchesCommittedFile is the reproducibility gate: running the
// generator must produce the committed generated.yaml byte for byte.
func TestBuildMatchesCommittedFile(t *testing.T) {
	t.Chdir("../..")

	cat, err := build()
	if err != nil {
		t.Fatalf("build: %v", err)
	}
	body, err := yaml.Marshal(cat)
	if err != nil {
		t.Fatal(err)
	}
	header := "# Code generated by tools/cataloggen; DO NOT EDIT.\n" +
		"# Sources: api/portainer-2.45.yaml, api/docker-engine-1.57.yaml, api/toolsets.yaml, api/default-tools.yaml.\n"
	want, err := os.ReadFile("internal/catalog/generated.yaml")
	if err != nil {
		t.Fatal(err)
	}
	if !bytes.Equal(append([]byte(header), body...), want) {
		t.Fatal("generated.yaml differs from a fresh run; run: make catalog")
	}
}

// TestEveryOperationHasOneTool checks the counts the stage promises: one tool
// per operation of both documents (websocket paths excluded) plus the raw
// extras, no duplicates, every toolset populated.
func TestEveryOperationHasOneTool(t *testing.T) {
	t.Chdir("../..")

	cat, err := build()
	if err != nil {
		t.Fatalf("build: %v", err)
	}
	seen := map[string]string{}
	total, defaults, extras := 0, 0, 0
	for _, ts := range cat.Toolsets {
		if len(ts.Tools) == 0 {
			t.Fatalf("toolset %q is empty", ts.Name)
		}
		for _, tool := range ts.Tools {
			if prev, ok := seen[tool.Name]; ok {
				t.Fatalf("tool %q appears in %q and %q", tool.Name, prev, ts.Name)
			}
			seen[tool.Name] = ts.Name
			total++
			if tool.Default {
				defaults++
			}
			if tool.Operation.Raw {
				extras++
			}
		}
	}
	// 288 Portainer operations minus 4 websocket ones, 108 Docker operations
	// minus the websocket attach, three raw extras.
	if want := 288 - 4 + 108 - 1 + 3; total != want {
		t.Fatalf("total tools = %d, want %d", total, want)
	}
	if want := 87; defaults != want {
		t.Fatalf("default tools = %d, want %d", defaults, want)
	}
	if want := 3; extras != want {
		t.Fatalf("raw extras = %d, want %d", extras, want)
	}
	if want := 11; len(cat.Toolsets) != want {
		t.Fatalf("toolsets = %d, want %d", len(cat.Toolsets), want)
	}
}

func TestToolName(t *testing.T) {
	m := mapping{Aliases: map[string]string{"git_ops": "gitops"}}
	cases := []struct {
		id, path, method, want string
	}{
		{"ContainerList", "/containers/json", "GET", "container_list"},
		{"ContainerCreate", "/containers/create", "POST", "container_create"},
		{"ContainerInspect", "/containers/{id}/json", "GET", "container_inspect"},
		{"SystemInfo", "/info", "GET", "system_info"},
		{"GetKubernetesPodLogs", "/kubernetes/{id}/pods/{namespace}/{pod}/logs", "GET", "kubernetes_pod_logs"},
		{"GetAllKubernetesPods", "/kubernetes/{id}/pods", "GET", "kubernetes_pods_list"},
		{"GetKubernetesPod", "/kubernetes/{id}/pods/{namespace}/{pod}", "GET", "kubernetes_pod_inspect"},
		{"DeleteKubernetesPod", "/kubernetes/{id}/pods/{namespace}/{pod}", "DELETE", "kubernetes_pod_delete"},
		{"GitOpsSourcesList", "/gitops/sources", "GET", "gitops_sources_list"},
		{"MOTD", "/motd", "GET", "motd"},
		{"HelmList", "/templates/helm", "GET", "helm_list"},
		{"EndpointSnapshot", "/endpoints/{id}/snapshot", "POST", "endpoint_snapshot"},
	}
	for _, tc := range cases {
		op := &operation{source: "portainer", id: tc.id, method: tc.method, path: tc.path}
		got, err := toolName(m, op)
		if err != nil {
			t.Fatalf("%s: %v", tc.id, err)
		}
		if got != tc.want {
			t.Fatalf("%s = %q, want %q", tc.id, got, tc.want)
		}
	}
}

func TestSnakeWords(t *testing.T) {
	cases := map[string][]string{
		"ContainerList":    {"container", "list"},
		"LDAPCheck":        {"ldap", "check"},
		"GitOpsSources":    {"git", "ops", "sources"},
		"getAllKubernetes": {"get", "all", "kubernetes"},
		"EdgeJobTasksList": {"edge", "job", "tasks", "list"},
	}
	for in, want := range cases {
		got := snakeWords(in)
		if len(got) != len(want) {
			t.Fatalf("%s = %v, want %v", in, got, want)
		}
		for i := range want {
			if got[i] != want[i] {
				t.Fatalf("%s = %v, want %v", in, got, want)
			}
		}
	}
}
